// Copies egress prices and exit programs for AWS, Azure and Google Cloud from the EU Cloud Price Index
// into data/exit-data.json and data/exit-data.js (the same, as an ES module for the page). Usage: node scripts/update-data.mjs [path-or-url]
import { readFile, writeFile } from 'node:fs/promises';

const src = process.argv[2] ?? 'https://raw.githubusercontent.com/moveinfra/eu-cloud-prices/main/data/manual.json';
const read = async (s) => JSON.parse(s.startsWith('http') ? await (await fetch(s)).text() : await readFile(s, 'utf8'));
const manual = await read(src);
const index = await read(src.replace(/manual\.json$/, 'eu-cloud-prices.json'));
const names = { aws: 'AWS', azure: 'Microsoft Azure', gcp: 'Google Cloud' };

const out = {
  checked: manual.checked,
  source: 'https://github.com/moveinfra/eu-cloud-prices',
  usdPerEur: index.fx.usdPerEur,
  fxDate: index.fx.date,
  providers: {},
};
for (const [id, name] of Object.entries(names)) {
  const p = manual.providers[id];
  out.providers[id] = {
    name,
    egress: {
      currency: p.egress.currency,
      unit: p.egress.unit ?? 'GB',
      freeGBPerMonth: p.egress.freeGBPerMonth ?? 0,
      tiers: p.egress.tiers.map(({ fromGB, toGB, perGB }) => ({ fromGB, toGB, perGB })),
      source: p.egress.source,
    },
    exitProgram: p.exitWaiver,
  };
}
const json = JSON.stringify(out, null, 2);
await writeFile('data/exit-data.json', json + '\n');
await writeFile('data/exit-data.js', `// Generated by scripts/update-data.mjs. Do not edit.\nexport default ${json};\n`);
console.log('wrote data/exit-data.json, prices checked', out.checked);
